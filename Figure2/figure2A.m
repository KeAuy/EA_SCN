%% Figure 2A: error of the analytic approximations, lambda = 0.02
%
% Solves the buffer problem for 100 values of nu on a geometric grid and
% plots log10 of the r-averaged error against nu.
%
% Input : ../data/b0_lambda0p02_nu100.mat
% Output: bNum_figure2A.mat

clear; close all; clc;

figureDir = fileparts(mfilename('fullpath'));
addpath(fullfile(figureDir, '..'));
dataDir = fullfile(figureDir, '..', 'data');

lambda        = 0.02;
eta           = 1;
nGrid         = 100;
nNu           = 100;
tolerance     = 1e-4;
maxIterations = 500;
realBranch    = 60;

nuValues = logspace(-3, 2, nNu)';
grid     = buffer.geometricGrid(1e-3, 1e2, nGrid);
data     = load(fullfile(dataDir, 'b0_lambda0p02_nu100.mat'), 'b0');

bNum = buffer.solveGeometric(data.b0, lambda, nuValues, eta, grid, ...
    'Tolerance', tolerance, 'MaxIterations', maxIterations);
save(fullfile(figureDir, 'bNum_figure2A.mat'), 'bNum');

approx = buffer.approximations(grid.r, lambda, nuValues, eta, ...
    {'RBA2', 'Pade2', 'Linear', 'ExpSer', 'ExpPade', 'DblExpSer'}, ...
    'PadeRefine', true, 'PadeRealCoefficients', true, ...
    'RealBranchIndex', realBranch);

errors = { ...
    log10(buffer.meanError(bNum, approx.rba2)), ...
    log10(buffer.meanError(bNum, approx.pade2)), ...
    log10(buffer.meanError(bNum, approx.linear)), ...
    log10(buffer.meanError(bNum, approx.expSeries)), ...
    log10(buffer.meanError(bNum, real(approx.expPade))), ...
    log10(buffer.meanError(bNum, approx.doubleExpSeries))};

c = buffer.palette();
buffer.plotErrors(nuValues, errors, ...
    {'RBA2', 'Padé2', 'LIN', 'Exp-Pade', 'ExpSer', 'DblExp-Ser'}, ...
    'Styles', {'--', '--', ':', '-.', '-', '--'}, ...
    'Colors', {c.red, c.green, c.blue, c.black, c.black, c.magenta}, ...
    'LineWidths', [2.5 2.5 2.5 2.5 1.5 2.5], ...
    'Ranges', {[], [], [], [], 1:realBranch, []}, ...
    'Title', 'Error comparison with RBA2,Pade2,LIN,Exp-Pade,Exp-Ser,DblExp-Ser', ...
    'Subtitle', '\lambda = 0.02,  \eta = 1');
