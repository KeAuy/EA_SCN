%% Figure 2C: error of the analytic approximations, lambda = 20.
%
% Same construction as Figure 2A with a different method set.
%
% Output: figures/figure2C.png

clear; close all; clc;

figureDir = fileparts(mfilename('fullpath'));
addpath(fullfile(figureDir, '..'));

lambda        = 20;
eta           = 1;
nGrid         = 100;
nNu           = 100;
tolerance     = 1e-7;
maxIterations = 50;
realBranch    = 60;

nuValues = logspace(-3, 2, nNu)';
grid     = buffer.geometricGrid(1e-3, 1e2, nGrid);
b0       = buffer.generateB0( ...
    lambda, eta, nuValues, 'Verbose', false);

bNum = buffer.solveGeometric(b0, lambda, nuValues, eta, grid, ...
    'Tolerance', tolerance, 'MaxIterations', maxIterations, ...
    'Verbose', false);

approx = buffer.approximations(grid.r, lambda, nuValues, eta, ...
    {'Pade2', 'Linear', 'ExpSer', 'ExpPade', 'DblExpSer'}, ...
    'PadeRefine', true, 'PadeRealCoefficients', true, ...
    'RealBranchIndex', realBranch);

errors = { ...
    log10(buffer.meanError(bNum, approx.pade2)), ...
    log10(buffer.meanError(bNum, approx.linear)), ...
    log10(buffer.meanError(bNum, approx.expSeries)), ...
    log10(buffer.meanError(bNum, approx.expPade)), ...
    log10(buffer.meanError(bNum, approx.doubleExpSeries))};

c = buffer.palette();
ax = buffer.plotErrors(nuValues, errors, ...
    {'Pad茅2', 'LIN', 'ExpPade', 'ExpSer', 'DblExp-Ser'}, ...
    'Styles', {'--', ':', '-.', '-', '--'}, ...
    'Colors', {c.green, c.black, c.black, c.black, c.magenta}, ...
    'LineWidths', [2.5 2.5 2.5 1.5 2.5], ...
    'Ranges', {[], [], [], 1:realBranch, []}, ...
    'Title', 'Error comparison with Pade2, LIN, ExpPade, ExpSer and DBLExpSer', ...
    'Subtitle', '\lambda = 20,  \eta = 1');

buffer.saveFigure(ax.Parent, 'figure2C.png');
