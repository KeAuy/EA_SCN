%% Figure 4B: error comparison, lambda = 2.
%
% Same construction as Figure 4A with a different method set.
%
% Output: figures/figure4B.png

clear; close all; clc;

figureDir = fileparts(mfilename('fullpath'));
addpath(fullfile(figureDir, '..'));

lambda        = 2;
eta           = 1;
nGrid         = 100;
nNu           = 100;
tolerance     = 1e-7;
maxIterations = 1000;
realBranch    = 60;

nuValues = logspace(-3, 2, nNu)';
grid     = buffer.geometricGrid(1e-3, 1e2, nGrid);
b0       = buffer.generateB0( ...
    lambda, eta, nuValues, 'Verbose', false);

bNum = buffer.solveGeometric(b0, lambda, nuValues, eta, grid, ...
    'Tolerance', tolerance, 'MaxIterations', maxIterations, ...
    'Verbose', false);

approx = buffer.approximations(grid.r, lambda, nuValues, eta, ...
    {'DblExpSer', 'ExpVar', 'ExpGlobal', 'DblExpVar', 'DblExpGlobal'}, ...
    'PadeRefine', true, 'PadeRealCoefficients', true, ...
    'RealBranchIndex', realBranch);

errors = { ...
    log10(buffer.meanError(bNum, approx.doubleExpSeries)), ...
    log10(buffer.meanError(bNum, approx.expVar)), ...
    log10(buffer.meanError(bNum, approx.expGlobal)), ...
    log10(buffer.meanError(bNum, approx.doubleExpVar)), ...
    log10(buffer.meanError(bNum, approx.doubleExpGlobal))};

c = buffer.palette();
ax = buffer.plotErrors(nuValues, errors, ...
    {'DblExp-Ser', 'ExpVar', 'ExpGlobal', 'DblExp-Var', 'DblExp-Global'}, ...
    'Styles', {'--', '--', '-', ':.', '-'}, ...
    'Colors', {c.magenta, c.blue, c.blue, c.magenta, c.magenta}, ...
    'LineWidths', [2.5 2.5 2.5 2.5 1.5], ...
    'Title', {'Error comparison with DblExpSer, ExpVar, ExpGlobal', ...
              'DblExpVar and DblExpGlobal'}, ...
    'Subtitle', '\lambda = 2,  \eta = 1');

buffer.saveFigure(ax.Parent, 'figure4B.png');
