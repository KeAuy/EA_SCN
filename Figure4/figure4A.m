%% Figure 4A: error comparison, lambda = 0.02.
%
% Compares the numerical profile with RBA2, Pade2, DblExp-Ser, ExpVar,
% ExpGlobal, DblExp-Var and DblExp-Global; the minimum of DblExp-Ser is marked.
%
% Output: figures/figure4A.png

clear; close all; clc;

figureDir = fileparts(mfilename('fullpath'));
addpath(fullfile(figureDir, '..'));

lambda        = 0.02;
eta           = 1;
nGrid         = 100;
nNu           = 100;
tolerance     = 1e-7;
maxIterations = 50;
realBranch    = 60;

nuValues = logspace(-3, 2, nNu)';
grid     = buffer.geometricGrid(1e-3, 1e2, nGrid);
b0       = buffer.generateB0( ...
    lambda, eta, nuValues, 'Verbose', false);

bNum = buffer.solveGeometric(b0, lambda, nuValues, eta, grid, ...
    'Tolerance', tolerance, 'MaxIterations', maxIterations, ...
    'Verbose', false);

approx = buffer.approximations(grid.r, lambda, nuValues, eta, ...
    {'RBA2', 'Pade2', 'DblExpSer', 'ExpVar', 'ExpGlobal', ...
     'DblExpVar', 'DblExpGlobal'}, ...
    'PadeRefine', true, 'PadeRealCoefficients', true, ...
    'RealBranchIndex', realBranch);

errors = { ...
    log10(buffer.meanError(bNum, approx.rba2)), ...
    log10(buffer.meanError(bNum, approx.pade2)), ...
    log10(buffer.meanError(bNum, approx.doubleExpSeries)), ...
    log10(buffer.meanError(bNum, approx.expVar)), ...
    log10(buffer.meanError(bNum, approx.expGlobal)), ...
    log10(buffer.meanError(bNum, approx.doubleExpVar)), ...
    log10(buffer.meanError(bNum, approx.doubleExpGlobal))};

c = buffer.palette();
ax = buffer.plotErrors(nuValues, errors, ...
    {'RBA2', 'Pad茅2', 'DblExp-Ser', 'ExpVar', 'ExpGlobal', ...
     'DblExp-Var', 'DblExp-Global'}, ...
    'Styles', {'--', '--', '--', '--', '-', ':.', '-'}, ...
    'Colors', {c.red, c.green, c.magenta, c.blue, c.blue, c.magenta, ...
               c.magenta}, ...
    'LineWidths', [2.5 2.5 2.5 2.5 2.5 2.5 1.5], ...
    'MarkMinimum', 3, ...
    'Title', {'Error comparison with RBA2, Pad茅2, DblExp-Ser, ExpVar and', ...
              'ExpGlobal, DblExp-Var, DblExp-Global'}, ...
    'Subtitle', '\lambda = 0.02,  \eta = 1');

buffer.saveFigure(ax.Parent, 'figure4A.png');
