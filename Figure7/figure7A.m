%% Figure 7 A: method regions and error maps, eta = 1.
%
% Solves the buffer problem on a 100-by-100 (lambda, nu) grid and selects the
% approximation region with the rule of BUFFER.WINNERRULES (not by the smallest
% error), then plots the b- and c-error maps of the selected method.
%
% Output: figures/figure7A_winnerMap.png
%         figures/figure7A_bErrorMap.png
%         figures/figure7A_cErrorMap.png

clear; close all; clc;

figureDir = fileparts(mfilename('fullpath'));
addpath(fullfile(figureDir, '..'));
outDir = buffer.outputDir();

eta           = 1;
nGrid         = 100;
nLambda       = 100;
nNu           = 100;
tolerance     = 1e-5;
stepTolerance = 1e-12;
maxIterations = 500;

lambdaValues = logspace(-3, 2, nLambda)';
nuValues     = logspace(-3, 2, nNu)';
grid         = buffer.geometricGrid(1e-3, 1e2, nGrid);
b0           = buffer.generateB0Grid( ...
    lambdaValues, nuValues, eta, 'Verbose', false);

bNum = buffer.solveGeometricLambdaGrid(b0, lambdaValues, nuValues, ...
    eta, grid, 'Tolerance', tolerance, 'StepTolerance', stepTolerance, ...
    'MaxIterations', maxIterations, 'Verbose', false);

methodNames = {'Pade2', 'RBA2', 'DblExp-Global'};
approx = buffer.approximationsGrid(grid.r, lambdaValues, nuValues, eta, ...
    {'Pade2', 'RBA2', 'DblExpGlobal'}, ...
    'PadeRefine', true, 'PadeRefineMethod', 'newton', ...
    'PadeRealCoefficients', true);

alphaGlobal = buffer.doubleExpAlphaGrid(lambdaValues, nuValues, eta, 'global');
winner = buffer.winnerRules(lambdaValues, nuValues, eta, alphaGlobal, ...
    'RealAlphaTolerance', 1e-8);

colors = [0.1300 0.6900 0.3000; ...
          0.5500 0.1000 0.1000; ...
          0.9961 0.4844 0.9922];

deltaGlobal = buffer.doubleExpDiscriminant(lambdaValues, nuValues, eta, 'global');
contours = struct('Z', deltaGlobal, ...
    'Color', [0.85 0.65 0.00], 'LineWidth', 1.0);

buffer.plotWinnerMap(nuValues, lambdaValues, winner, methodNames, colors, ...
    'Title', sprintf('Method regions (\\eta = %g)', eta), ...
    'Contours', contours, ...
    'OutputFile', fullfile(outDir, 'figure7A_winnerMap.png'));

cNum = buffer.chargeDensityGrid(bNum, grid.r, nuValues);
cApprox = { ...
    buffer.chargeDensityGrid(approx.pade2, grid.r, nuValues), ...
    buffer.chargeDensityGrid(approx.rba2, grid.r, nuValues), ...
    buffer.chargeDensityGrid(approx.doubleExpGlobal, grid.r, nuValues)};

errorsB = cat(3, ...
    buffer.meanErrorGrid(bNum, real(approx.pade2)), ...
    buffer.meanErrorGrid(bNum, real(approx.rba2)), ...
    buffer.meanErrorGrid(bNum, real(approx.doubleExpGlobal)));

errorsC = cat(3, ...
    buffer.meanErrorGrid(cNum, real(cApprox{1}), 'log'), ...
    buffer.meanErrorGrid(cNum, real(cApprox{2}), 'log'), ...
    buffer.meanErrorGrid(cNum, real(cApprox{3}), 'log'));

selectedB = buffer.selectWinner(errorsB, winner);
selectedC = buffer.selectWinner(errorsC, winner);

buffer.plotErrorMap(nuValues, lambdaValues, log10(selectedB), ...
    'Levels', 8, 'ColorTicks', -9:1:-2, ...
    'Title', 'log_{10}||b_{num} - b_{approx}||, \eta = 1', ...
    'OutputFile', fullfile(outDir, 'figure7A_bErrorMap.png'));

buffer.plotErrorMap(nuValues, lambdaValues, log10(selectedC), ...
    'Levels', 7, 'ColorTicks', -9:1:-2, ...
    'Title', 'log_{10}||c_{num} - c_{approx}||, \eta = 1', ...
    'OutputFile', fullfile(outDir, 'figure7A_cErrorMap.png'));
