%% Figure 1A: numerical solution and closed-form approximations of b(r)
%
% Finite-difference/Newton solution of the buffer equation compared with the
% approximations of the paper (lambda = 0.1, nu = 0.1, eta = 1).
%
% See README.md in this folder for the model and the parameters.

clear; close all; clc;

figureDir = fileparts(mfilename('fullpath'));
addpath(fullfile(figureDir, '..'));

lambda = 0.1;
nu     = 0.1;
eta    = 1;
b0     = 0.131;

r = linspace(1e-3, 1e2, 50000)';

b = buffer.solveUniform(b0, lambda, nu, eta, r, ...
    'SwitchRadius', 3.0, 'Tolerance', 1e-8, 'MaxIterations', 125);

approx = buffer.approximations(r, lambda, nu, eta, ...
    {'RBA2', 'Pade', 'Pade2', 'ExpSer', 'ExpPade', 'DblExpSer'}, ...
    'PadeRefine', false, 'PadeRealCoefficients', false);

c = buffer.palette();

buffer.plotProfiles(r, ...
    {b, approx.rba2, approx.pade, approx.pade2, approx.expSeries, ...
     approx.expPade, approx.doubleExpSeries}, ...
    {'Numerical', 'RBA2', 'Padé', 'Padé2', 'Exp-Ser', 'EXP-Padé', ...
     'DblExp-Ser'}, ...
    'Styles', {'-', '--', '-', '--', '-', '--', '--'}, ...
    'Colors', {c.numerical, c.red, c.pade, c.pade, c.black, c.black, ...
               c.magenta}, ...
    'LineWidths', 2 * ones(1, 7), ...
    'Title', 'Numerical solution and analytical approximations', ...
    'Subtitle', '\lambda = 0.1, \nu = 0.1, \eta = 1', ...
    'YLim', [0.089 1], ...
    'YTicks', [0 0.2 0.4 0.6 0.8 1], ...
    'YTickLabels', {' ', '0.2', '0.4', '0.6', '0.8', '1'}, ...
    'LegendLocation', 'northwest');
