%% Figure 1C: numerical solution and closed-form approximations of b(r).
%
% Same comparison as Figure 1A for lambda = 1, nu = 10, eta = 1, including the
% linearised (LIN) solution.
%
% Output: figures/figure1C.png

clear; close all; clc;

figureDir = fileparts(mfilename('fullpath'));
addpath(fullfile(figureDir, '..'));

lambda = 1;
nu     = 10;
eta    = 1;
b0     = 0.735;

r = linspace(1e-3, 1e2, 50000)';

b = buffer.solveUniform(b0, lambda, nu, eta, r, ...
    'SwitchRadius', 1.0, 'Tolerance', 1e-10, 'MaxIterations', 25);

approx = buffer.approximations(r, lambda, nu, eta, ...
    {'Linear', 'Pade', 'Pade2', 'ExpSer', 'DblExpSer'}, ...
    'PadeRefine', false, 'PadeRealCoefficients', false);

c = buffer.palette();
ax = buffer.plotProfiles(r, ...
    {b, approx.linear, approx.pade, approx.pade2, approx.expSeries, ...
     approx.doubleExpSeries}, ...
    {'Numerical', 'LIN', 'Padé', 'Padé2', 'Exp-Ser', 'DblExp-Ser'}, ...
    'Styles', {'-', '-.', '-', '--', '-', '--'}, ...
    'Colors', {c.numerical, c.black, c.pade, c.pade, c.black, c.magenta}, ...
    'LineWidths', [2.5 1.25 2.5 2.5 2.5 2.5], ...
    'Title', 'Numerical solution and analytical approximations', ...
    'Subtitle', '\lambda = 1, \nu = 10, \eta = 1', ...
    'YLim', [0.73 1], ...
    'YTicks', [0.73 0.75 0.8 0.85 0.9 0.95 1], ...
    'YTickLabels', {' ', '0.75', '0.8', '0.85', '0.9', '0.95', '1'}, ...
    'LegendLocation', 'southeast');

buffer.saveFigure(ax.Parent, 'figure1C.png');
