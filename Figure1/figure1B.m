%% Figure 1B: numerical solution and closed-form approximations of b(r)
%
% Same comparison as Figure 1A for lambda = 0.1, nu = 10, eta = 1.
%
% See README.md in this folder for the model and the parameters.

clear; close all; clc;

figureDir = fileparts(mfilename('fullpath'));
addpath(fullfile(figureDir, '..'));

lambda = 0.1;
nu     = 10;
eta    = 1;
b0     = 0.37;

r = linspace(1e-3, 1e2, 50000)';

b = buffer.solveUniform(b0, lambda, nu, eta, r, ...
    'SwitchRadius', 1.0, 'Tolerance', 1e-11, 'MaxIterations', 25);

approx = buffer.approximations(r, lambda, nu, eta, ...
    {'Pade', 'Pade2', 'ExpSer', 'DblExpSer'}, ...
    'PadeRefine', false, 'PadeRealCoefficients', false);

c = buffer.palette();
buffer.plotProfiles(r, ...
    {b, approx.pade, approx.pade2, approx.expSeries, ...
     approx.doubleExpSeries}, ...
    {'Numerical', 'Padé', 'Padé2', 'Exp-Ser', 'DblExp-Ser'}, ...
    'Styles', {'-', '-', '--', '-', '--'}, ...
    'Colors', {c.numerical, c.pade, c.pade, c.black, c.magenta}, ...
    'LineWidths', 2.5 * ones(1, 5), ...
    'Title', 'Numerical solution and analytical approximations', ...
    'Subtitle', '\lambda = 0.1, \nu = 10, \eta = 1', ...
    'XTickLabels', {'10^{-3}', '10^{-2}', '10^{-1}', '10^{0}', '10', '10^{2}'}, ...
    'LegendLocation', 'southeast');
