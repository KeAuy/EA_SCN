%% Figure 3A: numerical solution and Exp/DblExp approximations.
%
% Uniform-grid solution for lambda = 0.1, nu = 0.1, eta = 1 compared with
% Pade2, Exp-Var, Exp-Global, DblExp-Var and DblExp-Global.
%
% Output: figures/figure3A.png

clear; close all; clc;

figureDir = fileparts(mfilename('fullpath'));
addpath(fullfile(figureDir, '..'));

lambda = 0.1;
nu     = 0.1;
eta    = 1;
b0     = 0.131;

r = linspace(1e-3, 1e2, 50000)';

b = buffer.solveUniform(b0, lambda, nu, eta, r, ...
    'SwitchRadius', [], 'Tolerance', 1e-8, 'MaxIterations', 25);

approx = buffer.approximations(r, lambda, nu, eta, ...
    {'Pade2', 'ExpVar', 'ExpGlobal', 'DblExpVar', 'DblExpGlobal'}, ...
    'PadeRefine', false, 'PadeRealCoefficients', true);

c = buffer.palette();
ax = buffer.plotProfiles(r, ...
    {b, approx.pade2, approx.expVar, approx.expGlobal, ...
     approx.doubleExpVar, approx.doubleExpGlobal}, ...
    {'Numerical', 'Padé2', 'Exp-Var', 'EXP-Global', 'DblExp-Var', ...
     'DblExp-Global'}, ...
    'Styles', {'-', '--', '--', '-', '--', '-'}, ...
    'Colors', {c.numerical, c.pade, c.blue, c.blue, c.magenta, c.magenta}, ...
    'LineWidths', [2 2.5 2 2 2 2], ...
    'Title', 'Numerical solution VS Analytical Approximation', ...
    'Subtitle', '\lambda = 0.1,\nu = 0.1, \eta = 1', ...
    'YLim', [0.089 1], ...
    'YTicks', [0 0.2 0.4 0.6 0.8 1], ...
    'YTickLabels', {' ', '0.2', '0.4', '0.6', '0.8', '1'}, ...
    'LegendLocation', 'southeast');

buffer.saveFigure(ax.Parent, 'figure3A.png');
