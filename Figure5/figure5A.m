%% Figure 5A: log-error of the charge-density profiles, lambda = 0.02
%
% Compares c = nu (b - 1) + 1/r for the numerical solution and the
% RBA2, Pade2, ExpPade, ExpGlobal, DblExp-Var and DblExp-Global
% approximations.
%
% Input : ../data/b0_lambda0p02_nu100.mat
% Output: bNum_figure5A.mat

clear; close all; clc;

figureDir = fileparts(mfilename('fullpath'));
addpath(fullfile(figureDir, '..'));
dataDir = fullfile(figureDir, '..', 'data');

lambda        = 0.02;
eta           = 1;
nGrid         = 100;
nNu           = 100;
tolerance     = 1e-7;
maxIterations = 500;
realBranch    = 60;

nuValues = logspace(-3, 2, nNu)';
grid     = buffer.geometricGrid(1e-3, 1e2, nGrid);
data     = load(fullfile(dataDir, 'b0_lambda0p02_nu100.mat'), 'b0');

bNum = buffer.solveGeometric(data.b0, lambda, nuValues, eta, grid, ...
    'Tolerance', tolerance, 'MaxIterations', maxIterations);
save(fullfile(figureDir, 'bNum_figure5A.mat'), 'bNum');

approx = buffer.approximations(grid.r, lambda, nuValues, eta, ...
    {'RBA2', 'Pade2', 'ExpPade', 'ExpGlobal', 'DblExpVar', ...
     'DblExpGlobal'}, ...
    'PadeRefine', true, 'PadeRealCoefficients', true, ...
    'RealBranchIndex', realBranch);

cNum = buffer.chargeDensity(bNum, grid.r, nuValues);
errors = { ...
    log10(buffer.meanError(cNum, buffer.chargeDensity(approx.rba2, grid.r, nuValues), 'log')), ...
    log10(buffer.meanError(cNum, buffer.chargeDensity(approx.pade2, grid.r, nuValues), 'log')), ...
    log10(buffer.meanError(cNum, buffer.chargeDensity(approx.expPade, grid.r, nuValues), 'log')), ...
    log10(buffer.meanError(cNum, buffer.chargeDensity(approx.expGlobal, grid.r, nuValues), 'log')), ...
    log10(buffer.meanError(cNum, buffer.chargeDensity(approx.doubleExpVar, grid.r, nuValues), 'log')), ...
    log10(buffer.meanError(cNum, buffer.chargeDensity(approx.doubleExpGlobal, grid.r, nuValues), 'log'))};

c = buffer.palette();
buffer.plotErrors(nuValues, errors, ...
    {'RBA2', 'Padé2', 'Exp-Pade', 'Exp-Global', 'DblExp-Var', ...
     'DblExp-Global'}, ...
    'Styles', {'--', '--', '-.', '-', ':', '-'}, ...
    'Colors', {c.red, c.green, c.black, c.blue, c.magenta, c.magenta}, ...
    'LineWidths', 2.5 * ones(1, 6), ...
    'Ranges', {[], [], 1:realBranch, [], [], []}, ...
    'Title', {'Error comparison with RBA2, Pade2, Exp-Pade and', ...
              'Exp-Global, DblExp-Var and DblExp-Global'}, ...
    'Subtitle', '\lambda = 0.02,  \eta = 1', ...
    'YLabel', 'log_{10}||c_{num} - c_{approx}||', ...
    'YLim', [-7 -1], ...
    'YTicks', [-7 -6 -5 -4 -3 -2 -1], ...
    'YTickLabels', {'-7', '-6', '-5', '-4', '-3', '-2', '-1'});
